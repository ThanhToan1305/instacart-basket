"""Publish immutable Gold from a verified pilot model; never fits or evaluates labels."""
import argparse
import csv
import hashlib
import json
import math
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4

from hdfs_pipeline.helpers import (ROOT, Hdfs, dump, now, require, valid_id,
                                   source_manifest, schema_signature)

TABLES = ('frequent_itemsets', 'association_rules', 'recommendation_lookup')


def publication_contract(model, etl, model_id, confidence):
    valid_id(model_id)
    require(model.get('status') == 'PASS' and model.get('model_run_id') == model_id,
            'Requested model must be PASS')
    base = source_manifest(etl, model['etl_run_id'], model['etl_root'])
    require(model['model_root'] == base + '/models/' + model_id, 'Model root lineage mismatch')
    catalog = etl['gold']['product_catalog']
    require(catalog['status'] == 'PASS' and catalog['uri'] == base + '/gold/product_catalog',
            'Catalog lineage/status mismatch')
    for name in ('orders', 'baskets'):
        require(model['inputs'][name] == etl['silver'][name], 'Model Silver lineage mismatch: ' + name)
    require(math.isfinite(confidence) and model['config']['min_confidence'] <= confidence <= 1,
            'Publish confidence must be >= confidence generated by training and <= 1')
    for name in ('training_baskets', 'frequent_itemsets', 'rules'):
        entry = model['artifacts'][name]
        require(entry['status'] == 'PASS' and entry['rows'] == model['counts'][name],
                'Artifact manifest count/status mismatch: ' + name)
        require(entry['uri'] == model['model_root'] + '/artifacts/' + name,
                'Artifact URI lineage mismatch: ' + name)
    return base


def checked_read(hdfs, entry):
    require(entry['uri'].startswith(hdfs.base + '/'), 'Input outside expected HDFS namespace')
    suffix = entry['uri'][len(hdfs.base) + 1:]
    require(hdfs.exists(suffix + '/_SUCCESS'), 'Missing _SUCCESS: ' + entry['uri'])
    frame = hdfs.spark.read.parquet(entry['uri'])
    require(schema_signature(frame.schema.jsonValue()) == schema_signature(entry['schema']),
            'Schema mismatch: ' + entry['uri'])
    require(frame.count() == entry['rows'], 'Count mismatch: ' + entry['uri'])
    return frame


def no_rows(frame, condition, message):
    require(frame.where(condition).limit(1).count() == 0, message)


def check_arrays(frame, columns):
    from pyspark.sql import functions as F
    from pyspark.sql.types import ArrayType, IntegerType
    for name in columns:
        require(isinstance(frame.schema[name].dataType, ArrayType) and
                isinstance(frame.schema[name].dataType.elementType, IntegerType),
                name + ' must be array<int>')
        no_rows(frame, F.col(name).isNull() |
                F.exists(name, lambda x: x.isNull() | (x <= 0)) |
                (F.size(name) != F.size(F.array_distinct(name))), 'Invalid array: ' + name)


def check_metrics(rules):
    from pyspark.sql import functions as F
    from pyspark.sql.types import DoubleType
    for name in ('support', 'confidence', 'lift'):
        require(isinstance(rules.schema[name].dataType, DoubleType), 'Expected double ' + name)
        invalid = F.col(name).isNull() | F.isnan(name) | (F.abs(F.col(name)) == float('inf'))
        invalid = invalid | ((F.col(name) <= 0) if name == 'lift' else ~F.col(name).between(0, 1))
        no_rows(rules, invalid, 'Invalid metric: ' + name)


def check_itemsets(frame, training_rows):
    from pyspark.sql import functions as F
    from pyspark.sql.types import LongType
    check_arrays(frame, ('items',))
    require(isinstance(frame.schema['freq'].dataType, LongType), 'freq must be long')
    no_rows(frame, F.col('freq').isNull() | ~F.col('freq').between(1, training_rows) |
            (F.size('items') == 0), 'Invalid itemset frequency/items')
    require(frame.select(F.sort_array('items').alias('items')).distinct().count() == frame.count(),
            'Duplicate itemsets')


def build_gold(raw_rules, catalog, confidence):
    from pyspark.sql import functions as F
    from pyspark.sql.types import IntegerType, StringType
    from pipeline.fpgrowth_helpers import useful_rules
    check_arrays(raw_rules, ('antecedent', 'consequent'))
    check_metrics(raw_rules)
    require(isinstance(catalog.schema['product_id'].dataType, IntegerType) and
            isinstance(catalog.schema['product_name'].dataType, StringType), 'Invalid catalog types')
    no_rows(catalog, F.col('product_id').isNull() | (F.col('product_id') <= 0) |
            F.col('product_name').isNull() | (F.trim('product_name') == ''), 'Invalid catalog mapping')
    require(catalog.select('product_id').distinct().count() == catalog.count(), 'Duplicate catalog ID')
    # Conflicting duplicate metrics cannot be resolved by nondeterministic dropDuplicates.
    canonical = raw_rules.withColumn('antecedent', F.sort_array('antecedent')).withColumn(
        'consequent', F.sort_array('consequent')).select('antecedent', 'consequent', 'support', 'confidence', 'lift').distinct()
    no_rows(canonical.groupBy('antecedent', 'consequent').count(), F.col('count') > 1,
            'Conflicting duplicate rule metrics')
    ids = raw_rules.select(F.explode(F.array_union('antecedent', 'consequent')).alias('product_id')).distinct()
    require(ids.join(catalog, 'product_id', 'left_anti').limit(1).count() == 0,
            'Missing catalog mapping for rule ID')
    final = useful_rules(canonical, confidence)
    for array in ('antecedent', 'consequent'):
        names = (final.select('rule_id', F.posexplode(array).alias('pos', 'product_id'))
                 .join(catalog, 'product_id', 'left').groupBy('rule_id')
                 .agg(F.sort_array(F.collect_list(F.struct('pos', 'product_name'))).alias('mapped'))
                 .select('rule_id', F.transform('mapped', lambda x: x['product_name']).alias(array + '_names')))
        final = final.join(names, 'rule_id', 'left')
    lookup = (final.withColumn('antecedent_size', F.size('antecedent'))
              .withColumn('antecedent_product_id', F.explode('antecedent'))
              .withColumn('recommended_product_id', F.element_at('consequent', 1)))
    return final, lookup


def validate_gold(itemsets, rules, lookup, catalog, training_rows, confidence):
    from pyspark.sql import functions as F
    check_itemsets(itemsets, training_rows)
    check_arrays(rules, ('antecedent', 'consequent'))
    check_metrics(rules)
    no_rows(rules, (F.size('antecedent') == 0) | (F.size('consequent') != 1) |
            (F.size(F.array_intersect('antecedent', 'consequent')) != 0) |
            (F.col('confidence') < confidence) | (F.col('lift') <= 1), 'Gold violates useful rule filter')
    expected_rules, expected_lookup = build_gold(rules.drop('rule_id', 'antecedent_names', 'consequent_names'),
                                                  catalog, confidence)
    require(rules.select('rule_id').distinct().count() == rules.count(), 'Duplicate Gold rule ID')
    for actual, expected, name, keys in ((rules, expected_rules, 'association_rules', ['rule_id']),
                                        (lookup, expected_lookup, 'recommendation_lookup',
                                         ['rule_id', 'antecedent_product_id'])):
        expected = expected.select(*actual.columns)
        require(schema_signature(actual.schema.jsonValue()) == schema_signature(expected.schema.jsonValue()),
                'Gold type mismatch: ' + name)
        require(actual.select(*keys).distinct().count() == actual.count(), 'Duplicate Gold keys: ' + name)
        condition = F.col('a.' + keys[0]) == F.col('e.' + keys[0])
        for key in keys[1:]:
            condition = condition & (F.col('a.' + key) == F.col('e.' + key))
        compared = actual.alias('a').join(expected.alias('e'), condition, 'full')
        invalid = F.col('a.' + keys[0]).isNull() | F.col('e.' + keys[0]).isNull()
        for column in actual.columns:
            invalid = invalid | ~F.col('a.' + column).eqNullSafe(F.col('e.' + column))
        require(compared.where(invalid).count() == 0, 'Gold values/mapping mismatch: ' + name)
    expected_rows = rules.agg(F.coalesce(F.sum(F.size('antecedent')), F.lit(0)).alias('n')).first()['n']
    require(lookup.count() == expected_rows, 'Lookup count differs from sum antecedent_size')
    return {'frequent_itemsets': itemsets.count(), 'association_rules': rules.count(),
            'recommendation_lookup': expected_rows}


def atomic_publish(hdfs, staging, final):
    require(not hdfs.exists(final), 'Publication exists; refusing overwrite')
    require(hdfs.exists(staging), 'Staging publication is missing')
    # FileContext Rename.NONE rejects an existing target atomically (unlike fs.rename).
    jvm = hdfs.spark._jvm
    options = hdfs.spark.sparkContext._gateway.new_array(jvm.org.apache.hadoop.fs.Options.Rename, 1)
    options[0] = jvm.org.apache.hadoop.fs.Options.Rename.NONE
    context = jvm.org.apache.hadoop.fs.FileContext.getFileContext(
        jvm.java.net.URI(hdfs.base), hdfs.spark._jsc.hadoopConfiguration())
    context.rename(hdfs.jpath(hdfs.uri(staging)), hdfs.jpath(hdfs.uri(final)), options)
    require(hdfs.exists(final) and not hdfs.exists(staging), 'Atomic publication rename failed')


def charts(rules, folder, min_support):
    from pyspark.sql import functions as F
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import plotly.express as px
    maximum = rules.agg(F.max('lift').alias('m')).first()['m']
    width = max(((maximum or 1) - 1) / 20, 1e-9)
    histogram = (rules.withColumn('bin', F.least(F.floor((F.col('lift') - 1) / width), F.lit(19)))
                 .groupBy('bin').count().withColumn('lift_from', F.lit(1) + F.col('bin') * width)
                 .withColumn('lift_to', F.col('lift_from') + width).orderBy('bin'))
    top = (rules.where(F.col('support') >= min_support)
           .orderBy(F.desc('lift'), F.desc('confidence'), F.desc('support'), 'rule_id').limit(20)
           .select('rule_id', 'antecedent', 'consequent', 'antecedent_names', 'consequent_names',
                   'support', 'confidence', 'lift'))
    results = []
    for name, frame, title, x, y in (
        ('lift_distribution', histogram, 'Useful rules: lift distribution', 'lift_from', 'count'),
        ('top_rules', top, f'Top lift rules; support >= {min_support:g}', 'rule_id', 'lift')):
        require(frame.limit(501).count() <= 500, 'Chart aggregate exceeds 500 rows')
        data = frame.toPandas()
        if name == 'top_rules':
            data['rule_label'] = [', '.join(r['antecedent_names']) + ' → ' + ', '.join(r['consequent_names'])
                                  for r in data.to_dict('records')]
            x = 'rule_label'
        data.to_csv(folder / (name + '.csv'), index=False)
        fig, axis = plt.subplots(figsize=(14, 9) if name == 'top_rules' else (10, 5))
        if not data.empty:
            if name == 'top_rules':
                axis.barh(data[x].astype(str), data[y])
                axis.invert_yaxis()
                axis.tick_params(axis='y', labelsize=7)
                axis.set_xlabel('Lift')
            else:
                axis.bar(data[x].astype(str), data[y])
                axis.tick_params(axis='x', labelrotation=90, labelsize=6)
        else:
            axis.text(.5, .5, 'No useful rules', ha='center')
        axis.set_title(title)
        fig.tight_layout()
        fig.savefig(folder / (name + '.png'), dpi=150)
        plt.close(fig)
        plot = (px.bar(data, x=y, y=x, orientation='h', title=title) if name == 'top_rules'
                else px.bar(data, x=x, y=y, title=title))
        if name == 'top_rules':
            plot.update_layout(yaxis={'autorange': 'reversed'}, height=800)
        plot.write_html(str(folder / (name + '.html')), include_plotlyjs=True)
        results.append({'name': name, 'rows': len(data), 'csv': str(folder / (name + '.csv')),
                        'png': str(folder / (name + '.png')), 'html': str(folder / (name + '.html'))})
    return results


def integration_check(baskets, rules, lookup, catalog, folder):
    from pyspark.sql import functions as F
    import pandas as pd
    sys.path.insert(0, str(ROOT / 'app'))
    from recommender import recommend
    # Find witnesses in real training baskets, without using any target labels.
    witnesses = (baskets.select('order_id', 'items', F.explode('items').alias('seed'))
                 .join(lookup, F.col('seed') == F.col('antecedent_product_id'))
                 .where((F.size(F.array_except('antecedent', 'items')) == 0) &
                        ~F.array_contains('items', F.col('recommended_product_id')))
                 .select('order_id').distinct().orderBy('order_id').limit(5)
                 .withColumn('witness', F.lit(1)))
    # Prefer up to five real witnesses, then fill from the first remaining baskets.
    # Avoid Union plans: Spark 4.2 on this runtime stalled after one Union branch.
    contexts = (baskets.join(witnesses, 'order_id', 'left')
                .orderBy(F.desc_nulls_last('witness'), 'order_id')
                .limit(15).select('order_id', 'items').localCheckpoint(eager=True))
    seeds = contexts.select(F.explode('items').alias('antecedent_product_id')).distinct()
    relevant = lookup.join(seeds, 'antecedent_product_id', 'left_semi')
    require(relevant.limit(5001).count() <= 5000, 'Integration lookup exceeds bounded 5000 rows')
    lookup_pd = relevant.toPandas()
    # Only rule IDs need a name map here; context names are not used by recommend.
    ids = relevant.select(F.explode(F.array_union('antecedent', 'consequent')).alias('product_id')).distinct()
    small_catalog = catalog.join(ids, 'product_id', 'left_semi')
    require(small_catalog.limit(10001).count() <= 10000, 'Integration catalog exceeds bounded 10000 rows')
    catalog_pd = small_catalog.toPandas()
    valid_ids = set(catalog_pd.product_id)
    require(contexts.count() <= 15, 'Integration contexts exceed 15')
    records = []
    for case in contexts.collect():
        selected = set(case['items'])
        first = recommend(selected, lookup_pd, pd.DataFrame(columns=['count', 'product_id', 'product_name']), catalog_pd)
        second = recommend(list(reversed(case['items'])), lookup_pd.iloc[::-1],
                           pd.DataFrame(columns=['count', 'product_id', 'product_name']), catalog_pd)
        products = first.product_id.tolist()
        require(products == second.product_id.tolist(), 'Unstable recommendation tie-break')
        require(len(products) <= 5 and len(products) == len(set(products)) and
                not selected.intersection(products) and set(products) <= valid_ids, 'Invalid recommendation')
        oracle = []
        for rule in lookup_pd.drop_duplicates('rule_id').to_dict('records'):
            if set(rule['antecedent']) <= selected and rule['recommended_product_id'] not in selected:
                oracle.append(rule)
        oracle.sort(key=lambda r: (-r['confidence'], -r['lift'], -r['support'], r['recommended_product_id']))
        expected = list(dict.fromkeys(int(r['recommended_product_id']) for r in oracle))[:5]
        require(products == expected, 'Full antecedent/ranking mismatch')
        records.append({'order_id': case['order_id'], 'context': case['items'],
                        'recommendations': products, 'rule_ids': first.rule_id.tolist(), 'status': 'PASS'})
    dump(folder / 'integration_cases.json', records)
    return {'status': 'PASS' if any(r['recommendations'] for r in records) else 'NO_APPLICABLE_RULE',
            'cases': len(records), 'cases_with_rules': sum(bool(r['recommendations']) for r in records),
            'scope': 'functional integration only; no quality metrics or target labels',
            'artifact': str(folder / 'integration_cases.json')}


def run_worker(folder):
    from pyspark.sql import SparkSession
    report_path = folder / 'report.json'
    report = json.loads(report_path.read_text(encoding='utf-8'))
    model = json.loads((folder / 'model_manifest.json').read_text(encoding='utf-8'))
    etl = json.loads((folder / 'etl_manifest.json').read_text(encoding='utf-8'))
    spark = None
    started = time.perf_counter()

    def stage(name, action):
        entry = {'name': name, 'status': 'RUNNING', 'started_at': now()}
        report['stages'].append(entry)
        dump(report_path, report)
        tick = time.perf_counter()
        try:
            result = action()
            entry['status'] = 'PASS'
            return result
        except BaseException as error:
            entry.update(status='FAIL', error=repr(error))
            raise
        finally:
            entry.update(seconds=round(time.perf_counter() - tick, 3), ended_at=now())
            dump(report_path, report)

    try:
        spark = (SparkSession.builder.master('local[2]').appName('InstacartHdfsPublish-' + report['publication_id'])
                 .config('spark.driver.memory', '1g').config('spark.task.cpus', '1')
                 .config('spark.sql.shuffle.partitions', '8')
                 .config('spark.sql.adaptive.enabled', 'false')
                 .config('spark.hadoop.fs.defaultFS', 'file:///')
                 .config('spark.hadoop.dfs.client.use.datanode.hostname', 'true').getOrCreate())
        spark.sparkContext.setLogLevel('WARN')
        report.update(spark_version=spark.version,
                      hadoop_client_version=str(spark._jvm.org.apache.hadoop.util.VersionInfo.getVersion()),
                      adaptive_enabled=False)
        hdfs = Hdfs(spark, model['model_root'])
        staging, final = report['staging_suffix'], report['final_suffix']
        require(not hdfs.exists(staging) and not hdfs.exists(final),
                'Publication/staging exists; preserve incomplete run and choose new publication ID')
        source = Hdfs(spark, model['etl_root'])
        frames = stage('verify_model_artifacts', lambda: {
            name: checked_read(hdfs, entry) for name, entry in model['artifacts'].items()})
        catalog = stage('verify_etl_catalog', lambda: checked_read(source, etl['gold']['product_catalog'])
                        .select('product_id', 'product_name'))
        confidence = report['min_confidence']
        check_itemsets(frames['frequent_itemsets'], model['counts']['training_baskets'])
        from pipeline.fpgrowth_helpers import basket_invalid
        require(basket_invalid(frames['training_baskets'], 2) == 0, 'Invalid training artifact')
        rules, lookup = stage('build_useful_rules_and_lookup', lambda: build_gold(frames['rules'], catalog, confidence))
        from pyspark import StorageLevel
        rules = rules.persist(StorageLevel.DISK_ONLY)
        lookup = lookup.persist(StorageLevel.DISK_ONLY)
        report['gold'] = {}

        def save_staging():
            saved = {}
            for name, frame in zip(TABLES, (frames['frequent_itemsets'], rules, lookup)):
                readback, info = hdfs.save(frame, staging + '/' + name, frame.count())
                report['gold'][name] = dict(info, uri=hdfs.uri(final + '/' + name))
                saved[name] = readback
            return saved
        staged = stage('write_staging_and_readback', save_staging)
        report['counts'] = stage('validate_staging_values', lambda: validate_gold(
            staged['frequent_itemsets'], staged['association_rules'], staged['recommendation_lookup'],
            catalog, model['counts']['training_baskets'], confidence))
        report['charts'] = stage('charts_from_real_rules', lambda: charts(staged['association_rules'], folder,
                                                                         report['plot_min_support']))
        report['integration'] = stage('real_basket_integration', lambda: integration_check(
            frames['training_baskets'], staged['association_rules'], staged['recommendation_lookup'], catalog, folder))
        hdfs.mkdir('gold')
        stage('atomic_rename', lambda: atomic_publish(hdfs, staging, final))

        def final_check():
            final_frames = {name: checked_read(hdfs, info) for name, info in report['gold'].items()}
            return validate_gold(final_frames['frequent_itemsets'], final_frames['association_rules'],
                                 final_frames['recommendation_lookup'], catalog,
                                 model['counts']['training_baskets'], confidence)
        require(stage('final_hdfs_reconciliation', final_check) == report['counts'], 'Final counts changed')
        with (folder / 'row_counts.csv').open('w', newline='', encoding='utf-8') as stream:
            writer = csv.DictWriter(stream, fieldnames=['table', 'rows', 'uri'])
            writer.writeheader()
            for name, info in report['gold'].items():
                writer.writerow({'table': name, 'rows': info['rows'], 'uri': info['uri']})
        report.update(status='PASS', availability='USEFUL_RULES' if report['counts']['association_rules'] else 'NO_USEFUL_RULES',
                      ended_at=now(), seconds=round(time.perf_counter() - started, 3))
        # This immutable HDFS manifest is the commit marker. A directory alone is not PASS.
        report['hdfs_manifest_uri'] = hdfs.uri(final + '/publication_manifest.json')
        dump(folder / 'publication_manifest.json', report)
        hdfs.upload(folder / 'publication_manifest.json', final + '/publication_manifest.json')
    except BaseException as error:
        report.update(status='FAIL', error=repr(error), recovery='Preserve staging/final artifacts; use a new publication ID')
        raise
    finally:
        report.update(ended_at=now(), seconds=round(time.perf_counter() - started, 3))
        dump(report_path, report)
        if spark is not None:
            spark.stop()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model-run-id')
    parser.add_argument('--publication-id')
    parser.add_argument('--min-confidence', type=float)
    parser.add_argument('--plot-min-support', type=float)
    parser.add_argument('--worker', help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        run_worker(Path(args.worker))
        return 0
    model_id = valid_id(args.model_run_id)
    model_path = ROOT / 'outputs/hdfs_models' / model_id / 'report.json'
    model_bytes = model_path.read_bytes()
    model = json.loads(model_bytes)
    etl_path = ROOT / 'outputs/hdfs_runs' / valid_id(model['etl_run_id']) / 'report.json'
    etl_bytes = etl_path.read_bytes()
    require(hashlib.sha256(etl_bytes).hexdigest() == model['etl_report_sha256'], 'ETL report fingerprint changed')
    etl = json.loads(etl_bytes)
    confidence = args.min_confidence if args.min_confidence is not None else model['config']['min_confidence']
    publication_contract(model, etl, model_id, confidence)
    plot_support = args.plot_min_support if args.plot_min_support is not None else model['config']['min_support']
    require(math.isfinite(plot_support) and 0 < plot_support <= 1, 'Invalid plot support')
    pub_id = valid_id(args.publication_id or datetime.now(timezone.utc).strftime('pub_%Y%m%dT%H%M%SZ_') + uuid4().hex[:8])
    folder = model_path.parent / 'publications' / pub_id
    folder.mkdir(parents=True, exist_ok=False)
    dump(folder / 'model_manifest.json', model)
    dump(folder / 'etl_manifest.json', etl)
    dump(folder / 'report.json', {
        'status': 'RUNNING', 'started_at': now(), 'stages': [], 'publication_id': pub_id,
        'model_run_id': model_id, 'etl_run_id': model['etl_run_id'], 'model_root': model['model_root'],
        'etl_root': model['etl_root'], 'inputs': model['artifacts'],
        'catalog_input': etl['gold']['product_catalog'],
        'model_report_sha256': hashlib.sha256(model_bytes).hexdigest(),
        'etl_report_sha256': hashlib.sha256(etl_bytes).hexdigest(),
        'training_baskets': model['counts']['training_baskets'], 'model_config': model['config'],
        'min_confidence': confidence, 'plot_min_support': plot_support,
        'filter': 'nonempty antecedent; single consequent; disjoint; positive unique IDs; lift>1; confidence threshold',
        'staging_suffix': '.publish_staging/' + pub_id, 'final_suffix': 'gold/' + pub_id,
        'scope': 'sample pilot publication; no refit; no label-based evaluation',
        'compute': 'Spark local[2], one Docker host', 'worker_log': str(folder / 'worker.log')})
    from hdfs_pipeline.train import supervise
    code = supervise(folder, model['config']['worker_timeout_seconds'], module='hdfs_pipeline.publish')
    print('REPORT=' + str(folder / 'report.json'), flush=True)
    return code


if __name__ == '__main__':
    sys.exit(main())
